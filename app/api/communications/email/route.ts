export const dynamic = "force-dynamic";
import { NextResponse } from "next/server";
import { requireAdminSession } from "@/lib/auth";
import { prisma } from "@/lib/prisma";
import { logAction } from "@/lib/audit";
import { requireResendConfig } from "@/lib/email";

export const runtime = "nodejs";

const RESEND_API_URL = "https://api.resend.com/emails";

export async function POST(req: Request) {
  try {
    const session = await requireAdminSession();
    const body = await req.json();
    const { recipient, subject, content, leadId, outreachId } = body;

    if (!recipient || !subject || !content) {
      return NextResponse.json({ success: false, error: "Recipient, subject, and content are required" }, { status: 400 });
    }

    const { apiKey, from } = requireResendConfig();

    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 10000);

    try {
      const res = await fetch(RESEND_API_URL, {
        method: "POST",
        headers: {
          Authorization: `Bearer ${apiKey}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          from,
          to: recipient,
          subject,
          text: content,
          html: `<div style="font-family:sans-serif;padding:20px;color:#111;">${content.replace(/\n/g, '<br>')}</div><hr><p style="font-size:11px;color:#666;">Generated by My Personal AI Business Agent • Chaurjahari & Karnali Province</p>`,
        }),
        signal: controller.signal,
      });

      if (!res.ok) {
        let detail = "";
        try {
          const body = await res.json();
          detail = body.message || JSON.stringify(body);
        } catch {
          detail = res.statusText;
        }
        throw new Error(`Resend API rejected the message (${res.status}): ${detail}`);
      }

      const data = await res.json();
      clearTimeout(timeoutId);

      const deliveryStatus = "SENT";
      const messageId = data.id ?? data.messageId ?? undefined;

      // Save/update outreach record
      const outreach = await prisma.outreach.create({
        data: {
          channel: "EMAIL",
          recipient,
          subjectEn: subject,
          contentEn: content,
          status: deliveryStatus,
          leadId: leadId || null,
        },
      });

      if (outreachId) {
        await prisma.outreach.update({
          where: { id: outreachId },
          data: { status: deliveryStatus },
        }).catch(() => {});
      }

      await logAction("communication.email.send", JSON.stringify({ recipient, subject, deliveryStatus, messageId }));
      return NextResponse.json({ success: true, deliveryStatus, messageId, outreachId: outreach.id });
    } finally {
      clearTimeout(timeoutId);
    }
  } catch (err: any) {
    console.error("POST /api/communications/email error", err);
    return NextResponse.json({ success: false, error: err?.message || String(err) }, { status: 500 });
  }
}
